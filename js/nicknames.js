document.addEventListener('DOMContentLoaded', () => {
  const grid = document.getElementById('nickname-grid');
  if (!grid) return;
  const modal = document.getElementById('nickname-note');
  const title = document.getElementById('note-title');
  const text = document.getElementById('note-text');
  const close = modal.querySelector('.modal-close');
  let filter = 'all';
  function render() {
    grid.innerHTML = '';
    nicknames.filter(n => filter === 'all' || n[2] === filter).forEach((n, i) => {
      const card = document.createElement('button');
      card.className = 'nickname-card';
      card.style.animationDelay = (i * 25) + 'ms';
      card.innerHTML = `<span class="emoji">${n[1]}</span><strong>${n[0]}</strong><small>нажми, здесь записка ♡</small>`;
      card.addEventListener('click', () => {
        title.textContent = n[0] + ' ' + n[1];
        text.textContent = n[3];
        modal.hidden = false;
        close.focus();
        if (window.LoveEffects) window.LoveEffects.burst(card, 12);
      });
      grid.appendChild(card);
    });
  }
  document.querySelectorAll('[data-filter]').forEach(btn => btn.addEventListener('click', () => {
    filter = btn.dataset.filter;
    document.querySelectorAll('[data-filter]').forEach(b => b.classList.toggle('active', b === btn));
    render();
  }));
  function closeModal(){modal.hidden=true}
  close.addEventListener('click', closeModal);
  modal.addEventListener('click', e => {if(e.target===modal)closeModal()});
  document.addEventListener('keydown', e => {if(e.key==='Escape')closeModal()});
  render();
});
